"""TeachingEnv — fixed-N-turn tutor/student dialog, transcript scored by an LLM judge.

Each task specifies `turns: N`. The env runs N student-tutor exchanges, then terminates.
The reward function in `TeachingRubric` reads the full transcript + the task's rubric
and scores it via the judge LLM.

Turn semantics:
- `turns: 1` ⇒ seed (turn 1's student message) → tutor responds → done. **No student LLM call.**
- `turns: N>1` ⇒ seed → tutor → [student → tutor]*(N-1) → done. Each non-seed student
  message is either a fixed message from the task's `fixed_student_followups` list, or
  generated by the student LLM if no fix is provided for that turn.

Tool-call dispatch (image_gen and friends): when the tutor calls a tool, env_response
returns ToolMessages and does not advance the turn counter.
"""

from __future__ import annotations

import json
import logging
from typing import Any

import verifiers as vf
from openai import AsyncOpenAI
from verifiers.types import ToolCall, ToolMessage
from verifiers.utils.tool_utils import convert_func_to_tool_def, is_valid_tool_content_parts

from teachingbench.dataset import build_dataset
from teachingbench.grader.judge import TeachingRubric
from teachingbench.multimodal import attach_media_to_first_user_message
from teachingbench.student.base import Student
from teachingbench.student.llm import LLMStudent
from teachingbench.tools import TOOLS

logger = logging.getLogger(__name__)


def load_environment(
    *,
    judge_client: AsyncOpenAI | None = None,
    judge_model: str = "gpt-5.4",
    student_client: AsyncOpenAI | None = None,
    student_model: str | None = None,
    default_turns: int = 4,
    max_turns: int = 32,
    pass_threshold: float = 0.6,
    task_filter: str | None = None,
    skip_judge: bool = False,
    tutor_system_prompt: str | None = None,
    tutor_system_prompt_name: str | None = None,
    **kwargs: Any,
) -> vf.Environment:
    """Verifiers entry point. Don't pin the tutor model here — Verifiers passes it into rollout.

    skip_judge=True runs rollouts but short-circuits the judge call to return 0.0 reward.
    Use this for batch-rollout-then-judge-later workflows.

    Teacher system prompt selection (modular — any combo of model + prompt
    + task can be rolled out):
    - `tutor_system_prompt_name`: name from `teacher_prompts.TEACHER_PROMPTS`
      (currently `"socratic"`, `"concise"`, `"materials_first"`). Looked up
      via `get_teacher_prompt`; unknown names resolve to empty string.
    - `tutor_system_prompt`: raw string override. Takes precedence over the
      name lookup. If both are None, the per-task `tutor_system_prompt`
      from meta.yaml is used (which defaults to empty).
    """
    from teachingbench.teacher_prompts import get_teacher_prompt

    if judge_client is None:
        judge_client = AsyncOpenAI()
    rubric = TeachingRubric(judge_client=judge_client, judge_model=judge_model, skip_judge=skip_judge)
    dataset = build_dataset(task_filter=task_filter)

    if tutor_system_prompt is None and tutor_system_prompt_name is not None:
        tutor_system_prompt = get_teacher_prompt(tutor_system_prompt_name)

    return TeachingEnv(
        dataset=dataset,
        rubric=rubric,
        judge_client=judge_client,
        judge_model=judge_model,
        student_client=student_client or judge_client,
        student_model=student_model or judge_model,
        default_turns=default_turns,
        max_turns=max_turns,
        pass_threshold=pass_threshold,
        tools=TOOLS,
        env_id="teachingbench",
        tutor_system_prompt_override=tutor_system_prompt,
        **kwargs,
    )


class TeachingEnv(vf.MultiTurnEnv):
    def __init__(
        self,
        *,
        judge_client: AsyncOpenAI,
        judge_model: str,
        student_client: AsyncOpenAI,
        student_model: str,
        default_turns: int = 4,
        tools: list[Any] | None = None,
        tutor_system_prompt_override: str | None = None,
        **kwargs: Any,
    ) -> None:
        self._tools = list(tools or [])
        self._tool_map = {
            getattr(t, "__name__", t.__class__.__name__): t for t in self._tools
        }
        tool_defs = [convert_func_to_tool_def(t) for t in self._tools] if self._tools else None

        super().__init__(tool_defs=tool_defs, **kwargs)

        self._judge_client = judge_client
        self._judge_model = judge_model
        self._student_client = student_client
        self._student_model = student_model
        self._default_turns = default_turns
        # Env-level override for the per-task tutor system prompt. When
        # set (non-empty), takes precedence over the task's own
        # `tutor_system_prompt` for every rollout in this env instance.
        self._tutor_system_prompt_override = tutor_system_prompt_override

    # ------------------------------------------------------------------ setup

    async def setup_state(self, state: vf.State) -> vf.State:
        info = _info_dict(state)
        materials = info.get("materials", "")
        materials_media = info.get("materials_media") or []
        topic = info.get("topic", "(unknown topic)")
        subject = info.get("subject", "(unknown subject)")
        turns = int(info.get("turns") or self._default_turns)
        # Env-level override wins over per-task setting when non-empty.
        # If both are None/empty, the prompt is empty (no teacher conditioning) —
        # matches DEFAULT_TUTOR_SYSTEM_PROMPT = "".
        tutor_system_prompt = (
            self._tutor_system_prompt_override
            if self._tutor_system_prompt_override
            else info.get("tutor_system_prompt", "")
        )
        student_system_prompt = info.get("student_system_prompt", "")
        fixed_followups = list(info.get("fixed_student_followups") or [])

        # Inject the tutor's per-task system prompt at the front of the prompt.
        state["prompt"] = _ensure_system(state["prompt"], tutor_system_prompt)

        # If the task references PDFs/images in _materials/, attach them to the seed
        # user message as multipart content blocks so the tutor model can read them.
        if materials_media:
            state["prompt"] = attach_media_to_first_user_message(state["prompt"], materials_media)

        state["materials"] = materials
        state["materials_media"] = materials_media
        state["topic"] = topic
        state["subject"] = subject
        state["turns"] = turns
        state["completed_turns"] = 0
        state["student_system_prompt"] = student_system_prompt
        state["fixed_student_followups"] = fixed_followups
        return state

    # ------------------------------------------------------------------ env_response

    async def env_response(self, messages: vf.Messages, state: vf.State, **_: Any) -> vf.Messages:
        assert isinstance(messages, list) and messages, "env_response called with empty messages"
        last = messages[-1]

        # 1) Tutor called tools — dispatch and feed results back. Don't advance the turn counter.
        tool_calls = _tool_calls(last)
        if tool_calls:
            return await self._dispatch_tools(tool_calls)

        # 2) Tutor produced a text turn — one student-tutor pair just completed.
        completed = int(state.get("completed_turns", 0) or 0) + 1
        state["completed_turns"] = completed
        target = int(state.get("turns") or self._default_turns)

        logger.info("teachingbench env_response completed=%d/%d", completed, target)

        if completed >= target:
            return await self._finalize(state, reason="turns_reached")

        # 3) Produce the next student message for turn (completed + 1).
        next_turn = completed + 1
        fixed = self._fixed_message_for_turn(state, next_turn)
        if fixed is not None:
            return [{"role": "user", "content": fixed}]

        next_msg = await self._call_student(messages, state)
        return [{"role": "user", "content": next_msg}]

    # ------------------------------------------------------------------ helpers

    async def _call_student(self, messages: vf.Messages, state: vf.State) -> str:
        student = LLMStudent(client=self._student_client, model=self._student_model)
        try:
            return await student.respond(
                _as_dicts(messages),
                topic=state.get("topic", ""),
                materials=state.get("materials", ""),
                system_prompt=state.get("student_system_prompt", ""),
            )
        except Exception as e:
            logger.warning("LLMStudent.respond failed (%s); using fallback question.", e)
            return "Could you say more about that?"

    def _fixed_message_for_turn(self, state: vf.State, turn_number: int) -> str | None:
        """`fixed_student_followups[i]` covers turn (i + 2). Turn 1 is the seed (already in prompt)."""
        if turn_number <= 1:
            return None  # turn 1 is the seed, set in state["prompt"] at setup_state time
        followups = state.get("fixed_student_followups") or []
        idx = turn_number - 2
        if 0 <= idx < len(followups):
            return str(followups[idx])
        return None

    async def _finalize(self, state: vf.State, *, reason: str) -> vf.Messages:
        state["finalize_reason"] = reason
        # Emit a sentinel final message and signal termination to the rollout loop.
        completed = int(state.get("completed_turns", 0) or 0)
        target = int(state.get("turns") or self._default_turns)
        msg = {"role": "user", "content": f"[Session ended: {reason} (completed {completed}/{target} turns).]"}
        state["final_env_response"] = [msg]
        return [msg]

    async def _dispatch_tools(self, tool_calls: list[Any]) -> vf.Messages:
        results: list[Any] = []
        for tc in tool_calls:
            name = _tc_field(tc, "name")
            args_raw = _tc_field(tc, "arguments") or "{}"
            tc_id = _tc_field(tc, "id") or ""
            try:
                args = json.loads(args_raw) if isinstance(args_raw, str) else (args_raw or {})
            except json.JSONDecodeError as e:
                results.append(ToolMessage(role="tool", content=f"tool args parse error: {e}", tool_call_id=tc_id))
                continue
            tool = self._tool_map.get(name)
            if tool is None:
                results.append(ToolMessage(role="tool", content=f"unknown tool: {name}", tool_call_id=tc_id))
                continue
            try:
                result = await tool(**args)
            except Exception as e:
                results.append(ToolMessage(role="tool", content=f"tool error: {e}", tool_call_id=tc_id))
                continue
            content = result if is_valid_tool_content_parts(result) else json.dumps(result)
            results.append(ToolMessage(role="tool", content=content, tool_call_id=tc_id))
        return results


# --- module-level helpers ---


def _info_dict(state: vf.State) -> dict[str, Any]:
    info = state.get("info") if isinstance(state, dict) else None
    if isinstance(info, str):
        try:
            return json.loads(info)
        except json.JSONDecodeError:
            return {}
    if isinstance(info, dict):
        return info
    return {}


def _ensure_system(prompt: Any, system_content: str) -> Any:
    """Prepend / replace the system message, OR strip any system messages if
    `system_content` is empty. Empty content reflects the realistic 'user opened
    ChatGPT and pasted the question' default — the model gets no system prompt at all.
    """
    has_content = bool((system_content or "").strip())
    if isinstance(prompt, list):
        non_system = [m for m in prompt if _role(m) != "system"]
        if has_content:
            return [{"role": "system", "content": system_content}] + non_system
        return non_system
    user_msg = {"role": "user", "content": str(prompt)}
    return [{"role": "system", "content": system_content}, user_msg] if has_content else [user_msg]


def _tool_calls(msg: Any) -> list[Any]:
    if isinstance(msg, dict):
        tc = msg.get("tool_calls") or []
    else:
        tc = getattr(msg, "tool_calls", None) or []
    return list(tc) if tc else []


def _tc_field(tc: Any, name: str) -> Any:
    if isinstance(tc, dict):
        return tc.get(name) if name == "id" else (tc.get("function", {}) or {}).get(name, tc.get(name))
    if isinstance(tc, ToolCall):
        return getattr(tc, name, None)
    return getattr(tc, name, None)


def _as_dicts(messages: vf.Messages) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for m in messages:
        if isinstance(m, dict):
            out.append(m)
        else:
            out.append({"role": _role(m), "content": _content(m)})
    return out


def _role(msg: Any) -> str:
    if isinstance(msg, dict):
        return str(msg.get("role", ""))
    return str(getattr(msg, "role", ""))


def _content(msg: Any) -> Any:
    if isinstance(msg, dict):
        return msg.get("content", "")
    return getattr(msg, "content", "")
